/* 把 37 个 <script src> 合并成一个 app.js，减少手机端请求数。
 * 用法：node scripts/build-site.mjs
 * 说明：听力音频的 data URI 不再随首屏加载；full.js 会按需请求 assets/audio/**.mp3。
 *       脚本清单在 scripts/site.scripts.json；改完 assets/js 或 data 后要重新构建。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const indexPath = path.join(root, 'index.html');
const manifestPath = path.join(root, 'scripts', 'site.scripts.json');
const distDir = path.join(root, 'assets', 'dist');
const bundlePath = path.join(distDir, 'app.js');

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const scripts = manifest.scripts || [];
if (!scripts.length) throw new Error('scripts/site.scripts.json 为空');

const parts = [];
for (const src of scripts) {
  const file = path.join(root, src.replace(/\//g, path.sep));
  if (!fs.existsSync(file)) throw new Error('找不到脚本：' + src);
  parts.push('/* ===== ' + src + ' ===== */\n' + fs.readFileSync(file, 'utf8'));
}

fs.mkdirSync(distDir, { recursive: true });
const bundle = '/* StudyHub bundle: ' + scripts.length + ' scripts. Generated by scripts/build-site.mjs. */\n' +
  parts.join('\n;\n') + '\n';
fs.writeFileSync(bundlePath, bundle, 'utf8');

let html = fs.readFileSync(indexPath, 'utf8');
html = html.replace(/<script[^>]*src="[^"]+"[^>]*><\/script>\s*/g, '');
html = html.replace('</body>', '  <script defer src="assets/dist/app.js"></script>\n  <script defer src="assets/js/sync.js"></script>\n</body>');
fs.writeFileSync(indexPath, html, 'utf8');

console.log('已生成：' + bundlePath);
console.log('bundle：' + (Buffer.byteLength(bundle) / 1024).toFixed(1) + ' KB；合并 ' + scripts.length + ' 个脚本');
console.log('index.html 已改为只加载 app.js + sync.js');