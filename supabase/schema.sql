-- StudyHub · Supabase 数据库初始化
-- 在 Supabase Dashboard → SQL Editor 里整段粘贴并 Run。
-- 设计：表不直接开放给 anon；只开放两个 RPC，同步码相当于密钥。

create table if not exists public.studyhub_progress (
  code text primary key,
  data jsonb not null,
  rev integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.studyhub_history (
  id bigint generated by default as identity primary key,
  code text not null,
  rev integer not null,
  data jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists studyhub_history_code_rev_idx
  on public.studyhub_history (code, rev desc);

alter table public.studyhub_progress enable row level security;
alter table public.studyhub_history enable row level security;

-- 表本身不允许 anon 直接读写；只能通过下面的 RPC。
revoke all on public.studyhub_progress from anon, authenticated;
revoke all on public.studyhub_history from anon, authenticated;

create or replace function public.studyhub_get(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.studyhub_progress%rowtype;
begin
  if p_code is null or p_code !~ '^[A-Za-z0-9_-]{8,64}$' then
    return jsonb_build_object('ok', false, 'error', 'bad_code');
  end if;

  select * into r from public.studyhub_progress where code = p_code;
  if not found then
    return jsonb_build_object('ok', true, 'exists', false, 'rev', 0);
  end if;

  return jsonb_build_object(
    'ok', true,
    'exists', true,
    'data', r.data,
    'rev', r.rev,
    'updatedAt', r.updated_at
  );
end;
$$;

create or replace function public.studyhub_save(
  p_code text,
  p_data jsonb,
  p_base_rev integer default null,
  p_force boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  cur public.studyhub_progress%rowtype;
begin
  if p_code is null or p_code !~ '^[A-Za-z0-9_-]{8,64}$' then
    return jsonb_build_object('ok', false, 'error', 'bad_code');
  end if;
  if p_data is null or jsonb_typeof(p_data) <> 'object' then
    return jsonb_build_object('ok', false, 'error', 'bad_data');
  end if;
  if pg_column_size(p_data) > 2 * 1024 * 1024 then
    return jsonb_build_object('ok', false, 'error', 'too_large');
  end if;

  if not p_force and p_base_rev is not null and p_base_rev > 0 then
    select * into cur from public.studyhub_progress where code = p_code;
    if not found then
      return jsonb_build_object('ok', false, 'error', 'not_found');
    end if;
    if cur.rev <> p_base_rev then
      return jsonb_build_object(
        'ok', false, 'conflict', true,
        'current', jsonb_build_object('data', cur.data, 'rev', cur.rev)
      );
    end if;
  end if;

  insert into public.studyhub_progress (code, data, rev)
  values (p_code, p_data, 1)
  on conflict (code) do update
    set data = excluded.data,
        rev = public.studyhub_progress.rev + 1,
        updated_at = now()
    where p_force
       or p_base_rev is null
       or p_base_rev = 0
       or public.studyhub_progress.rev = p_base_rev
  returning * into cur;

  if cur.code is null then
    select * into cur from public.studyhub_progress where code = p_code;
    return jsonb_build_object(
      'ok', false, 'conflict', true,
      'current', jsonb_build_object('data', cur.data, 'rev', cur.rev)
    );
  end if;

  insert into public.studyhub_history (code, rev, data)
  values (p_code, cur.rev, p_data);

  delete from public.studyhub_history
  where code = p_code
    and id not in (
      select id from public.studyhub_history
      where code = p_code
      order by rev desc
      limit 50
    );

  return jsonb_build_object('ok', true, 'rev', cur.rev, 'updatedAt', cur.updated_at);
end;
$$;

grant execute on function public.studyhub_get(text) to anon;
grant execute on function public.studyhub_save(text, jsonb, integer, boolean) to anon;